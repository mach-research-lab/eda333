	la t0, y_matrix #Pointer to matrix
	li t1, 1 #Counter for whole matrix        
	li t2, 196       
	li t3, 1 #Counter for row lenth	 
	li t4, WOUT_MAX
print_loop:
 	flw fa0, 0(t0) #Load value
 	li a7, 2 
 	ecall
 	bne t3, t4, print_comma
 	print_char ('\n')
 	li t3, 0 #0 instead of 1 because it will be incremented	before next iteration
 	b print_increment
print_comma:
 	print_char (',')
 	print_char (' ')
print_increment:
 	addi t0, t0, 4 #Every float is 4 bytes
 	addi t1, t1, 1 
 	addi t3, t3, 1	
 	ble t1, t2, print_loop
	ret



