# This is an example macro that can be used to load a float value from the X matrix using regular indexing instead of pointer arithmetic.
# It helps with readability but you should know that this particular macro is relatively inefficient. Note that it modifies registers t0 and t1
# Also note that a macro is not a subroutine, a macro will be converted into inline code wherever it is used.
# Usage: x_matrix_load (fa0, s0, s1, s2)
.macro x_matrix_load (%destReg, %rowIndexReg, %colIndexReg, %cIndexReg)
	la t0, x_matrix 		# Base address
	
	li t1, 1024			# Size of sub-matrix
	mul t1, %cIndexReg, t1		# Calculate address offset
	add t0, t0, t1			# Base address of sub-matrix
	
	li t1, W 			# width
	mul t1, %rowIndexReg, t1	# row * width
	add t1, t1, %colIndexReg	# + col
	slli t1, t1, 2			# * 4 (size of float)
	
	add t0, t0, t1			# final address
	flw %destReg, 0(t0)		# load float
.end_macro


